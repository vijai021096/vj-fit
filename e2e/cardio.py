import asyncio, re
from playwright.async_api import async_playwright
URL='http://localhost:4173'
fails=[]
def check(n, ok, extra=''):
    print(('PASS ' if ok else 'FAIL ')+n, extra)
    if not ok: fails.append(n)
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch()
        ctx=await b.new_context(viewport={'width':430,'height':932},is_mobile=True,has_touch=True,reduced_motion='reduce')
        pg=await ctx.new_page(); errs=[]; pg.on('pageerror',lambda e: errs.append(str(e)))
        await pg.goto(URL); await pg.wait_for_timeout(800)
        await pg.get_by_text('I understand').click(); await pg.wait_for_timeout(300)
        await pg.get_by_text('Start as Vikas').click(); await pg.get_by_text('Build my plan').click(); await pg.wait_for_timeout(700)
        await pg.get_by_role('button',name='Got it').click(); await pg.wait_for_timeout(600)
        await pg.get_by_role('button',name='I’m Vikas').click(); await pg.wait_for_timeout(400)
        await pg.get_by_role('button',name='Library',exact=True).click(); await pg.wait_for_timeout(800)
        await pg.get_by_role('button',name='Cardio',exact=True).click(); await pg.wait_for_timeout(400)
        await pg.get_by_role('button',name=re.compile('Treadmill Walk')).first.click(); await pg.wait_for_timeout(800)
        check('timer card shown', await pg.get_by_test_id('cardio-timer').count()==1)
        await pg.get_by_role('button',name='Start').first.click(); await pg.wait_for_timeout(1500)
        await pg.reload(); await pg.wait_for_timeout(1500)
        st=await pg.evaluate("JSON.parse(localStorage.getItem('v2fit-store')).state.quick")
        check('running timer survives reload', bool(st and st['startedAt']), st)
        await pg.get_by_role('button',name='Library',exact=True).click(); await pg.wait_for_timeout(600)
        await pg.get_by_role('button',name='Cardio',exact=True).click(); await pg.wait_for_timeout(300)
        await pg.get_by_role('button',name=re.compile('Treadmill Walk')).first.click(); await pg.wait_for_timeout(1000)
        check('shows Pause after reload', await pg.get_by_role('button',name='Pause').count()==1)
        await pg.wait_for_timeout(10500)
        await pg.get_by_role('button',name='Save').click(); await pg.wait_for_timeout(800)
        check('entry listed', await pg.get_by_text('Cardio logged today').count()==1)
        check('quick cleared', await pg.evaluate("JSON.parse(localStorage.getItem('v2fit-store')).state.quick")is None)
        await pg.screenshot(path='/home/claude/qa/98-cardio.png')
        await pg.get_by_role('button',name=re.compile('^Remove')).click(); await pg.wait_for_timeout(500)
        check('entry removable', await pg.get_by_text('Cardio logged today').count()==0)
        check('no page errors', not errs, errs)
        await b.close()
    print('FAILS:',fails)
asyncio.run(main())
